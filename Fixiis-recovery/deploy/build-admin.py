#!/usr/bin/env python3
"""Inline the Admin redesign modules into Admin.html.

The admin panel is shipped as ONE self-contained file: it has to work when the
operator double-clicks it, when it is served by the backend, and when the
standalone build copies it somewhere else. So the design system and the shell
runtime live as separate, reviewable sources under ``admin/`` and are compiled
into ``Admin.html`` between sentinel comments.

    python3 deploy/build-admin.py            # write Admin.html
    python3 deploy/build-admin.py --check    # fail if Admin.html is stale

Sources
    admin/design-system.css   tokens + primitives
    admin/admin-shell.css     application frame
    admin/screens.css         per-screen treatments
    admin/reactor.js          the dashboard core (2D canvas)
    admin/shell.js            navigation, command bar, search, notifications
    admin/dashboard.js        command-centre data binding
    admin/screens.js          logs, files, KLG, LPV, Telegram behaviours
    admin/dashboard.html      the command-centre markup

The compile is idempotent: running it twice produces the same bytes, and it
never touches anything outside the marked regions (so application logic in
Admin.html can never be damaged by a rebuild).
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ADMIN = ROOT / "Admin.html"

# region marker -> source file
REGIONS = {
    "SHF:DS:CSS": "admin/design-system.css",
    "SHF:SHELL:CSS": "admin/admin-shell.css",
    "SHF:SCREENS:CSS": "admin/screens.css",
    "SHF:REACTOR:JS": "admin/reactor.js",
    "SHF:SHELL:JS": "admin/shell.js",
    "SHF:DASHBOARD:JS": "admin/dashboard.js",
    "SHF:SCREENS:JS": "admin/screens.js",
    "SHF:DASH:HTML": "admin/dashboard.html",
}

GENERATED_NOTE = "Generated by deploy/build-admin.py"


def _begin(key: str) -> str:
    return f"/* {key}:BEGIN */" if key.endswith("CSS") or key.endswith("JS") else f"<!-- {key}:BEGIN -->"


def _end(key: str) -> str:
    return f"/* {key}:END */" if key.endswith("CSS") or key.endswith("JS") else f"<!-- {key}:END -->"


def _read_source(rel: str) -> str:
    path = ROOT / rel
    if not path.is_file():
        raise SystemExit(f"build-admin: missing source {rel}")
    body = path.read_text(encoding="utf-8").rstrip("\n")
    if "</style" in body.lower() or "</script" in body.lower():
        # Inlining markup that closes its own container would break the page in
        # a way no test would catch until an operator opened it.
        raise SystemExit(f"build-admin: {rel} contains a closing tag it must not")
    return body


def build(html: str) -> str:
    out = html
    for key, rel in REGIONS.items():
        begin, end = _begin(key), _end(key)
        if begin not in out or end not in out:
            raise SystemExit(f"build-admin: markers for {key} not found in Admin.html")
        body = _read_source(rel)
        start = out.index(begin) + len(begin)
        stop = out.index(end, start)
        out = out[:start] + "\n" + body + "\n" + out[stop:]
    return out


def digest(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:12]


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true",
                    help="verify Admin.html is up to date instead of writing it")
    args = ap.parse_args(argv)

    original = ADMIN.read_text(encoding="utf-8")
    if GENERATED_NOTE not in original:
        raise SystemExit("build-admin: Admin.html has no generated regions")

    built = build(original)

    if args.check:
        if built == original:
            print(f"admin build up to date ({digest(original)})")
            return 0
        print("admin build is STALE — run: python3 deploy/build-admin.py")
        return 1

    if built == original:
        print(f"admin build unchanged ({digest(built)})")
        return 0

    ADMIN.write_text(built, encoding="utf-8")
    print(f"admin build written ({digest(built)})  "
          f"{len(original):,} -> {len(built):,} bytes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
