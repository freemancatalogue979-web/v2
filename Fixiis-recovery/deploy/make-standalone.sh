#!/usr/bin/env bash
# ============================================================================
# Produce standalone copies of the front-ends pointed at YOUR server.
#
# The panels in this repo talk to whatever origin serves them by default.
# This bakes your backend URL into a copy so you can:
#   - double-click it and run it straight off your disk (file://), or
#   - drop it on any static host (Netlify, Pages, S3, a shared drive)
# ...and it will still find your server.
#
#   ./deploy/make-standalone.sh http://YOUR-SERVER:8446
#   ./deploy/make-standalone.sh https://panel.example.com ./my-panels
#
# Output goes to ./standalone/ (or the directory you pass) and is
# gitignored, so your server address never ends up in a commit.
#
# Prefer not to generate files at all? Just append a query string:
#   file:///path/to/mini-admin.html?server=http://YOUR-SERVER:8446
# ============================================================================
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
SERVER="${1:-}"
OUTDIR="${2:-$here/standalone}"

if [[ -z "$SERVER" ]]; then
    echo "usage: $0 <server-url> [output-dir]" >&2
    echo "  e.g. $0 http://YOUR-SERVER:8446" >&2
    exit 1
fi

# Normalise: bare host gets a scheme, trailing slashes are dropped.
if [[ ! "$SERVER" =~ ^[a-zA-Z][a-zA-Z0-9+.-]*:// ]]; then
    echo "no scheme given — assuming http://" >&2
    SERVER="http://$SERVER"
fi
SERVER="${SERVER%/}"

mkdir -p "$OUTDIR"

emit() {
    local src="$1" dst="$2" label="$3"
    [[ -f "$src" ]] || { echo "  skip  $label (not found)"; return; }

    python3 - "$src" "$dst" "$SERVER" <<'PY'
import re, sys
src, dst, server = sys.argv[1], sys.argv[2], sys.argv[3]
html = open(src, encoding='utf-8').read()
tag = "<script>window.SERVER_ENDPOINT=%s;</script>" % repr(server).replace("'", '"')
m = re.search(r'<head[^>]*>', html, re.I)
if not m:
    sys.exit("no <head> in " + src)
# Only a previously *injected* tag is a problem. The panels also contain
# the string in the code that reads window.SERVER_ENDPOINT, which is not
# an injection, so match the assignment specifically.
if re.search(r'window\.SERVER_ENDPOINT\s*=', html):
    sys.stderr.write("  note  %s was already baked — re-baking\n" % src)
open(dst, 'w', encoding='utf-8').write(
    html[:m.end()] + "\n" + tag + html[m.end():]
)
PY
    printf '  ok    %-22s -> %s\n' "$label" "$dst"
}

echo "Baking server: $SERVER"
echo "Output:        $OUTDIR"
echo

emit "$here/mini-admin.html" "$OUTDIR/mini-admin.html" "mini-admin.html"
emit "$here/Admin.html"      "$OUTDIR/Admin.html"      "Admin.html"
emit "$here/client.html"     "$OUTDIR/client.html"     "client.html"

cat > "$OUTDIR/README.txt" <<EOF
Standalone panels — generated by deploy/make-standalone.sh

Server: $SERVER

Open any of these by double-clicking, or upload them to any static host.

  mini-admin.html   compact panel (phone-friendly)
  Admin.html        full panel
  client.html       the injected client page (only needed if you serve it
                    yourself instead of letting the server inject it)

Logging in
  Use the same username and password as the server's admin login.

If a panel will not connect
  1. Check the server is reachable:  curl $SERVER/api/settings
  2. If you are opening this from an HTTPS page (Netlify, Pages, ...) the
     browser will BLOCK an http:// backend as mixed content. Either put
     HTTPS on the server, or open these files directly from disk.
  3. The first time you open one, it remembers the server in localStorage.
     To point it somewhere else, add ?server=<new-url> to the file path.

Regenerate any time with:
  ./deploy/make-standalone.sh $SERVER
EOF

echo
echo "  ok    README.txt"
echo
echo "Done. Open $OUTDIR/mini-admin.html to start."

# Mixed content is the most common failure; warn when it applies.
if [[ "$SERVER" == http://* ]]; then
    echo
    echo "  warning: backend is plain HTTP."
    echo "           Fine from file:// or another http:// page, but a page"
    echo "           served over HTTPS will be blocked by the browser."
fi
